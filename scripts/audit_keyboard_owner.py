def audit(data):
    if hashlib.sha256(data).hexdigest()!=ORIGINAL:raise ValueError('requires exact original January SHA256')
    pe=PE(data)
    for at,value,label in SITES:
        expected=bytes.fromhex(value)
        if pe.read(at,len(expected))!=expected:raise ValueError('witness mismatch: '+label)
        if label.startswith('scoped load '):
            base=label.rsplit('_',1)[1]
            register={'eax':0,'ecx':1,'edx':2}[base]
            if pe.read(at-3,3)!=bytes((0x8B,0x45+(register<<3),0xF8)):
                raise ValueError('index base is not this from EBP-8: '+label)
    return {'status':'PASS','witnesses':len(SITES),'scoped_index_loads':196,'game_executed':False}
